/**
 * scripts/sync-editor-css.mjs
 * ---------------------------------------------------------------------------
 * Copies the MDXEditor stylesheet out of node_modules and into
 * `public/vendor/mdxeditor.css`.
 *
 * WHY THIS EXISTS
 * ---------------
 * The Pages Router only allows *global* (non-module) CSS to be imported from
 * `_app.tsx`. That meant `@mdxeditor/editor/style.css` was concatenated into
 * the single site-wide CSS bundle — ~56 KB of editor chrome (toolbar,
 * CodeMirror, diff view, dialogs) shipped as render-blocking CSS to every
 * visitor of every public page, even though the editor only ever mounts on
 * `/admin/posts/*` behind an auth cookie.
 *
 * Serving it from `public/` instead lets `MdxEditor.tsx` pull it in with a
 * plain <link> at the moment the editor actually mounts (it is already
 * `dynamic(..., { ssr: false })`), so the bytes follow the component.
 *
 * Kept in sync automatically via the `prebuild` / `predev` npm hooks, so a
 * `@mdxeditor/editor` upgrade can never leave a stale copy behind.
 * ---------------------------------------------------------------------------
 */
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dest = path.join(root, "public", "vendor", "mdxeditor.css");

const HEADER = `/* AUTO-GENERATED by scripts/sync-editor-css.mjs — do not edit.
   Source: @mdxeditor/editor/dist/style.css
   Loaded on demand by src/components/admin/MdxEditor.tsx (admin-only). */\n`;

async function main() {
  let src;
  try {
    src = require.resolve("@mdxeditor/editor/dist/style.css");
  } catch {
    // Resolution through the package `exports` map, if the deep path is not
    // exported in a future version.
    src = path.join(
      path.dirname(require.resolve("@mdxeditor/editor/package.json")),
      "dist",
      "style.css",
    );
  }

  const css = await readFile(src, "utf8");
  await mkdir(path.dirname(dest), { recursive: true });
  await writeFile(dest, HEADER + css, "utf8");

  const kb = (Buffer.byteLength(css) / 1024).toFixed(1);
  console.log(`sync-editor-css: ${kb} KB → public/vendor/mdxeditor.css`);
}

main().catch((err) => {
  console.error("sync-editor-css failed:", err.message);
  process.exit(1);
});
